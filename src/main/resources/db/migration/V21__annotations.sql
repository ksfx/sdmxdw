-- SDMX annotations (#15): id, type, title, text and URL on structure artefacts, as in SDMX. Generic
-- on purpose - a table layout (LAYOUT_ROW, LAYOUT_COLUMN, ... in the conventions of the .Stat Suite)
-- is just one use. The target is a structure row identified by its kind and id, so there is no
-- foreign key (structure artefacts are never deleted).
CREATE TABLE annotation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type     VARCHAR(30) NOT NULL CHECK (target_type IN ('DATAFLOW', 'DSD', 'DIMENSION',
                        'CODELIST', 'CODE', 'CONCEPT_SCHEME', 'CONCEPT', 'CATEGORY_SCHEME', 'CATEGORY')),
    target_id       BIGINT NOT NULL,
    position        INTEGER NOT NULL DEFAULT 0,
    annotation_id   VARCHAR(255),
    annotation_type VARCHAR(255),
    title           TEXT,
    text            TEXT,
    url             TEXT,
    updated_by      VARCHAR(255) NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX annotation_target_ix ON annotation (target_type, target_id, position);
