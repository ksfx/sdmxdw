-- Generic container for register-style microdata (one row per entity per
-- reporting period, e.g. an individual loan), as opposed to the SDMX cube
-- model (series/observation) used for aggregate statistics. Field catalogs
-- differ per microdata source and evolve over time, so the record payload
-- is kept as free-form JSON text (same convention as
-- observation.measure_values_json) instead of a fixed wide column set.
--
-- No partitioning in V1: unlike observation, no concrete volume requirement
-- exists yet for any microdata source. Range-partitioning by
-- reporting_period can be added later without a full rewrite once real
-- volume is known.
CREATE TABLE microdata_flow (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id VARCHAR(64) NOT NULL,
    artefact_id VARCHAR(64) NOT NULL,
    version VARCHAR(32) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    linked_dataflow_id BIGINT REFERENCES dataflow (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (agency_id, artefact_id, version)
);

-- facet_slot ('facet1'..'facet4') marks a field whose value is copied into
-- the matching indexed column on microdata_record at ingest time, so the
-- record browser can filter in SQL instead of scanning JSON payloads.
CREATE TABLE microdata_field_definition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    microdata_flow_id BIGINT NOT NULL REFERENCES microdata_flow (id),
    field_code VARCHAR(128) NOT NULL,
    label VARCHAR(255) NOT NULL,
    data_type VARCHAR(20) NOT NULL CHECK (data_type IN ('STRING', 'NUMBER', 'DATE', 'BOOLEAN')),
    codelist_id BIGINT REFERENCES codelist (id),
    required BOOLEAN NOT NULL DEFAULT FALSE,
    facet_slot VARCHAR(10) CHECK (facet_slot IN ('facet1', 'facet2', 'facet3', 'facet4')),
    position INT NOT NULL,
    UNIQUE (microdata_flow_id, field_code),
    UNIQUE (microdata_flow_id, facet_slot)
);

-- Bitemporal like observation: valid_from/valid_to track the current
-- version of one (flow, entity_id, reporting_period, stage) record;
-- resubmissions close the old vintage instead of overwriting it.
CREATE TABLE microdata_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    microdata_flow_id BIGINT NOT NULL REFERENCES microdata_flow (id),
    entity_id VARCHAR(128) NOT NULL,
    reporting_period VARCHAR(32) NOT NULL DEFAULT '',
    stage VARCHAR(10) NOT NULL CHECK (stage IN ('ALPHA', 'BETA')),
    facet1_value VARCHAR(255),
    facet2_value VARCHAR(255),
    facet3_value VARCHAR(255),
    facet4_value VARCHAR(255),
    payload_json TEXT NOT NULL,
    valid_from TIMESTAMPTZ NOT NULL,
    valid_to TIMESTAMPTZ,
    recorded_by VARCHAR(255) NOT NULL
);

CREATE UNIQUE INDEX microdata_record_current_uq
    ON microdata_record (microdata_flow_id, entity_id, reporting_period, stage)
    WHERE valid_to IS NULL;

CREATE INDEX microdata_record_current_filter_ix
    ON microdata_record (microdata_flow_id, stage, facet1_value, facet2_value, facet3_value, facet4_value)
    WHERE valid_to IS NULL;

CREATE INDEX microdata_record_history_ix
    ON microdata_record (microdata_flow_id, entity_id, reporting_period, stage, valid_from);
