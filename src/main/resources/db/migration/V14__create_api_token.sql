-- Personal API tokens for script access to the read API (/rest/**). Only a SHA-256 hash of the
-- token is stored; the plain token is shown once at creation. A token acts with the role of its
-- owner, looked up on every request, so a role change or deleted user takes effect immediately.
CREATE TABLE api_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    token_hint VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ,
    last_used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ
);

CREATE INDEX api_token_user_ix ON api_token (user_id);
