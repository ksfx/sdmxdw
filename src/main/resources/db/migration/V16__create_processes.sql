-- Processes (#20): metadata in the database, code in the process folder (later a Git repo).
-- Replaces import_job/import_job_run; the old tables are migrated at startup by
-- LegacyImportMigration and dropped in a later migration.

CREATE TABLE process (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL UNIQUE,
    description TEXT,
    -- sub-folder of the process folder holding this process' code
    folder VARCHAR(100) NOT NULL UNIQUE CHECK (folder ~ '^[a-z0-9][a-z0-9_-]*$'),
    -- Spring cron (6 fields), null = manual only
    schedule VARCHAR(100),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    timeout_minutes INT NOT NULL DEFAULT 30 CHECK (timeout_minutes BETWEEN 1 AND 1440),
    notify_email VARCHAR(255),
    -- start automatically after a successful run of this process
    run_after_process_id BIGINT REFERENCES process (id) ON DELETE SET NULL,
    -- comma-separated names of secrets passed to the steps as environment variables
    secret_names VARCHAR(1000) NOT NULL DEFAULT '',
    -- JSON list of parameter definitions [{name,label,defaultValue,required}]
    params_json TEXT NOT NULL DEFAULT '[]',
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE process_step (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id BIGINT NOT NULL REFERENCES process (id) ON DELETE CASCADE,
    position INT NOT NULL,
    step_key VARCHAR(50) NOT NULL CHECK (step_key ~ '^[a-z0-9][a-z0-9_-]*$'),
    type VARCHAR(20) NOT NULL CHECK (type IN ('SCRIPT', 'AGGREGATE', 'PROMOTE', 'PROCESS')),
    -- SCRIPT: path relative to the process folder (.py or .R)
    script_path VARCHAR(500),
    args VARCHAR(2000) NOT NULL DEFAULT '',
    -- AGGREGATE / PROMOTE: flow reference, e.g. SNB:DF_KRED(3.0.0)
    target VARCHAR(300),
    -- PROCESS: the process run as a sub-process
    sub_process_id BIGINT REFERENCES process (id),
    -- comma-separated step keys this step waits for (default: the previous step)
    needs VARCHAR(500) NOT NULL DEFAULT '',
    UNIQUE (process_id, position),
    UNIQUE (process_id, step_key)
);

CREATE TABLE process_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id BIGINT NOT NULL REFERENCES process (id) ON DELETE CASCADE,
    parent_run_id BIGINT REFERENCES process_run (id) ON DELETE CASCADE,
    trigger VARCHAR(20) NOT NULL CHECK (trigger IN ('SCHEDULED', 'MANUAL', 'CHAINED', 'SUB_PROCESS')),
    triggered_by VARCHAR(255) NOT NULL,
    params_json TEXT NOT NULL DEFAULT '{}',
    dry_run BOOLEAN NOT NULL DEFAULT FALSE,
    commit_sha VARCHAR(64),
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCESS', 'FAILURE', 'CANCELLED')),
    message TEXT,
    queued_at TIMESTAMPTZ NOT NULL,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);

CREATE INDEX process_run_process_ix ON process_run (process_id, queued_at DESC);
CREATE INDEX process_run_status_ix ON process_run (status) WHERE status IN ('QUEUED', 'RUNNING');

CREATE TABLE process_step_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES process_run (id) ON DELETE CASCADE,
    position INT NOT NULL,
    step_key VARCHAR(50) NOT NULL,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('PENDING', 'RUNNING', 'SUCCESS', 'FAILURE', 'SKIPPED', 'CANCELLED')),
    exit_code INT,
    log TEXT NOT NULL DEFAULT '',
    -- JSON: per target flow rows read / written / unchanged, or validation errors
    load_report TEXT,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);

CREATE INDEX process_step_run_run_ix ON process_step_run (run_id, position);

-- Write-only secrets (AES-GCM encrypted with a server-side key), injected into steps by name.
CREATE TABLE process_secret (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE CHECK (name ~ '^[A-Z][A-Z0-9_]*$'),
    value_encrypted TEXT NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

-- Audit entries can now also belong to a process (metadata changes, loads).
ALTER TABLE audit_log ADD COLUMN process_id BIGINT REFERENCES process (id) ON DELETE CASCADE;
ALTER TABLE audit_log DROP CONSTRAINT audit_log_one_resource;
ALTER TABLE audit_log ADD CONSTRAINT audit_log_one_resource
    CHECK (num_nonnulls(dataflow_id, microdata_flow_id, process_id) = 1);
CREATE INDEX audit_log_process_ix ON audit_log (process_id, performed_at);
