-- A series is the unique combination of non-time dimension values within a
-- dataflow (SDMX "key"). Time, where the DSD has a DATE-typed dimension, is
-- kept out of the series key and lives on the observation instead, since V1
-- treats time as a normal optional dimension rather than a special axis.
CREATE TABLE series (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    dataflow_id BIGINT NOT NULL REFERENCES dataflow (id),
    series_key TEXT NOT NULL,
    UNIQUE (dataflow_id, series_key)
);

-- Bitemporal observations: valid_from/valid_to track when a recorded value
-- was the current one for its (series, time_period, stage); past vintages
-- are never deleted or overwritten, only closed via valid_to.
--
-- Partitioned by HASH(dataflow_id) into a fixed set of partitions so that
-- new dataflows never require new partition DDL. Time-range sub-partitioning
-- was left out for V1 to keep the migration manageable; revisit once real
-- data volume is known (Postgres supports attaching range sub-partitions
-- later without a rewrite).
CREATE TABLE observation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    dataflow_id BIGINT NOT NULL REFERENCES dataflow (id),
    series_id BIGINT NOT NULL REFERENCES series (id),
    time_period VARCHAR(50) NOT NULL DEFAULT '',
    stage VARCHAR(10) NOT NULL CHECK (stage IN ('ALPHA', 'BETA')),
    measure_values_json TEXT NOT NULL,
    valid_from TIMESTAMPTZ NOT NULL,
    valid_to TIMESTAMPTZ,
    recorded_by VARCHAR(255) NOT NULL,
    PRIMARY KEY (id, dataflow_id)
) PARTITION BY HASH (dataflow_id);

CREATE TABLE observation_p0 PARTITION OF observation FOR VALUES WITH (MODULUS 8, REMAINDER 0);
CREATE TABLE observation_p1 PARTITION OF observation FOR VALUES WITH (MODULUS 8, REMAINDER 1);
CREATE TABLE observation_p2 PARTITION OF observation FOR VALUES WITH (MODULUS 8, REMAINDER 2);
CREATE TABLE observation_p3 PARTITION OF observation FOR VALUES WITH (MODULUS 8, REMAINDER 3);
CREATE TABLE observation_p4 PARTITION OF observation FOR VALUES WITH (MODULUS 8, REMAINDER 4);
CREATE TABLE observation_p5 PARTITION OF observation FOR VALUES WITH (MODULUS 8, REMAINDER 5);
CREATE TABLE observation_p6 PARTITION OF observation FOR VALUES WITH (MODULUS 8, REMAINDER 6);
CREATE TABLE observation_p7 PARTITION OF observation FOR VALUES WITH (MODULUS 8, REMAINDER 7);

-- Enforces "exactly one current vintage per series/time/stage"; dataflow_id
-- must be part of the index because it is the partition key.
CREATE UNIQUE INDEX observation_current_uq
    ON observation (dataflow_id, series_id, time_period, stage)
    WHERE valid_to IS NULL;

CREATE INDEX observation_history_ix ON observation (series_id, time_period, stage, valid_from);

CREATE TABLE audit_log (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    dataflow_id BIGINT NOT NULL REFERENCES dataflow (id),
    action VARCHAR(50) NOT NULL,
    performed_by VARCHAR(255) NOT NULL,
    performed_at TIMESTAMPTZ NOT NULL,
    details TEXT
);
