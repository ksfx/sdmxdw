-- Microdata partitioned by flow and reporting period (#17).
--
-- A delivery of 5 million records took longer the larger the table already was, because every
-- index of the whole table was maintained (539 s into 10 GB, 687 s into 33 GB). Now records are
-- stored in one partition per flow and reporting period:
--   microdata_record                         LIST (microdata_flow_id)
--     microdata_record_f<flow>               LIST (reporting_period)
--       microdata_record_f<flow>_<period>    one period of one flow, Alpha and Beta
-- A quarterly delivery writes into new, small partitions; queries of a flow (explorer, read API)
-- only touch that flow's partitions; old periods can be detached and archived.
--
-- PostgreSQL does not create partitions by itself: microdata_ensure_partition() creates the
-- partition of a flow and period before records are written. The application calls it in a
-- short transaction of its own, because creating a partition briefly locks the whole table.
-- microdata_partition lists the partitions (also used for the reporting periods of a flow).

CREATE TABLE microdata_partition (
    microdata_flow_id BIGINT NOT NULL REFERENCES microdata_flow (id),
    reporting_period  VARCHAR(32) NOT NULL,
    table_name        TEXT NOT NULL UNIQUE,
    PRIMARY KEY (microdata_flow_id, reporting_period)
);

CREATE FUNCTION microdata_ensure_partition(p_flow BIGINT, p_period TEXT) RETURNS void AS $$
DECLARE
    flow_table TEXT := 'microdata_record_f' || p_flow;
    part       TEXT;
BEGIN
    IF EXISTS (SELECT 1 FROM microdata_partition
               WHERE microdata_flow_id = p_flow AND reporting_period = p_period) THEN
        RETURN;
    END IF;
    PERFORM pg_advisory_xact_lock(7171717, p_flow::int);  -- concurrent creators of the same flow
    IF EXISTS (SELECT 1 FROM microdata_partition
               WHERE microdata_flow_id = p_flow AND reporting_period = p_period) THEN
        RETURN;
    END IF;
    IF to_regclass(flow_table) IS NULL THEN
        EXECUTE format('CREATE TABLE %I PARTITION OF microdata_record FOR VALUES IN (%s)'
                       || ' PARTITION BY LIST (reporting_period)', flow_table, p_flow);
    END IF;
    part := left(flow_table || '_' || regexp_replace(lower(p_period), '[^a-z0-9]+', '_', 'g'), 52)
            || '_' || substr(md5(p_period), 1, 6);
    EXECUTE format('CREATE TABLE %I PARTITION OF %I FOR VALUES IN (%L)', part, flow_table, p_period);
    INSERT INTO microdata_partition VALUES (p_flow, p_period, part);
END;
$$ LANGUAGE plpgsql;

-- reporting periods with current records of a stage: one index probe per partition
CREATE FUNCTION microdata_periods(p_flow BIGINT, p_stage TEXT) RETURNS SETOF TEXT AS $$
DECLARE
    r     RECORD;
    found BOOLEAN;
BEGIN
    FOR r IN SELECT reporting_period, table_name FROM microdata_partition
             WHERE p_flow IS NULL OR microdata_flow_id = p_flow LOOP
        EXECUTE format('SELECT EXISTS (SELECT 1 FROM %I WHERE stage = $1 AND valid_to IS NULL)',
                       r.table_name) INTO found USING p_stage;
        IF found THEN
            RETURN NEXT r.reporting_period;
        END IF;
    END LOOP;
END;
$$ LANGUAGE plpgsql STABLE;

-- move the records into the partitioned table
ALTER TABLE microdata_record RENAME TO microdata_record_unpartitioned;
ALTER INDEX microdata_record_pkey RENAME TO microdata_record_unpartitioned_pkey;
ALTER INDEX microdata_record_current_filter_ix RENAME TO microdata_record_unpartitioned_filter_ix;
ALTER INDEX microdata_record_current_order_ix RENAME TO microdata_record_unpartitioned_order_ix;
ALTER INDEX microdata_record_current_uq RENAME TO microdata_record_unpartitioned_uq;
ALTER INDEX microdata_record_entity_trgm_ix RENAME TO microdata_record_unpartitioned_trgm_ix;
ALTER INDEX microdata_record_history_ix RENAME TO microdata_record_unpartitioned_history_ix;
ALTER TABLE microdata_pending DROP CONSTRAINT microdata_pending_record_id_fkey;

CREATE TABLE microdata_record (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    microdata_flow_id BIGINT NOT NULL REFERENCES microdata_flow (id),
    entity_id         VARCHAR(128) NOT NULL,
    reporting_period  VARCHAR(32) NOT NULL DEFAULT '',
    stage             VARCHAR(10) NOT NULL CHECK (stage IN ('ALPHA', 'BETA')),
    facet1_value      VARCHAR(255),
    facet2_value      VARCHAR(255),
    facet3_value      VARCHAR(255),
    facet4_value      VARCHAR(255),
    payload_json      TEXT NOT NULL,
    valid_from        TIMESTAMPTZ NOT NULL,
    valid_to          TIMESTAMPTZ,
    recorded_by       VARCHAR(255) NOT NULL,
    comment           TEXT
) PARTITION BY LIST (microdata_flow_id);

SELECT microdata_ensure_partition(microdata_flow_id, reporting_period)
FROM (SELECT DISTINCT microdata_flow_id, reporting_period FROM microdata_record_unpartitioned) p;

INSERT INTO microdata_record SELECT * FROM microdata_record_unpartitioned;
SELECT setval(pg_get_serial_sequence('microdata_record', 'id'),
              greatest((SELECT max(id) FROM microdata_record), 1));
DROP TABLE microdata_record_unpartitioned;

-- unique keys of a partitioned table contain its partition columns
ALTER TABLE microdata_record ADD PRIMARY KEY (id, microdata_flow_id, reporting_period);
CREATE UNIQUE INDEX microdata_record_current_uq
    ON microdata_record (microdata_flow_id, entity_id, reporting_period, stage) WHERE valid_to IS NULL;
CREATE INDEX microdata_record_current_filter_ix
    ON microdata_record (microdata_flow_id, stage, facet1_value, facet2_value, facet3_value, facet4_value)
    WHERE valid_to IS NULL;
CREATE INDEX microdata_record_current_order_ix
    ON microdata_record (stage, microdata_flow_id, reporting_period, entity_id) INCLUDE (id)
    WHERE valid_to IS NULL;
CREATE INDEX microdata_record_history_ix
    ON microdata_record (microdata_flow_id, entity_id, reporting_period, stage, valid_from);
CREATE INDEX microdata_record_entity_trgm_ix
    ON microdata_record USING gin (entity_id gin_trgm_ops) WITH (gin_pending_list_limit = 65536)
    WHERE valid_to IS NULL;

CREATE TRIGGER microdata_pending_insert AFTER INSERT ON microdata_record
    REFERENCING NEW TABLE AS new_rows
    FOR EACH STATEMENT EXECUTE FUNCTION microdata_pending_after_insert();
CREATE TRIGGER microdata_pending_update AFTER UPDATE ON microdata_record
    REFERENCING NEW TABLE AS new_rows
    FOR EACH STATEMENT EXECUTE FUNCTION microdata_pending_after_update();

-- partitioned tables are never analysed by autovacuum; the planner needs their statistics
ANALYZE microdata_record;
