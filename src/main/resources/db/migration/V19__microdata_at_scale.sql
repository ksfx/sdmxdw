ALTER TABLE microdata_record RENAME TO microdata_record_unpartitioned;
ALTER INDEX microdata_record_pkey RENAME TO microdata_record_unpartitioned_pkey;
ALTER INDEX microdata_record_current_filter_ix RENAME TO microdata_record_unpartitioned_filter_ix;
ALTER INDEX microdata_record_current_uq RENAME TO microdata_record_unpartitioned_uq;
ALTER INDEX microdata_record_history_ix RENAME TO microdata_record_unpartitioned_history_ix;

CREATE TABLE microdata_record (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    microdata_flow_id BIGINT NOT NULL REFERENCES microdata_flow (id),
    entity_id         VARCHAR(128) NOT NULL,
    reporting_period  VARCHAR(32) NOT NULL DEFAULT '',
    stage             VARCHAR(10) NOT NULL CHECK (stage IN ('ALPHA', 'BETA')),
    facet1_value      VARCHAR(255),
    facet2_value      VARCHAR(255),
    facet3_value      VARCHAR(255),
    facet4_value      VARCHAR(255),
    payload_json      TEXT NOT NULL,
    valid_from        TIMESTAMPTZ NOT NULL,
    valid_to          TIMESTAMPTZ,
    recorded_by       VARCHAR(255) NOT NULL,
    comment           TEXT
) PARTITION BY LIST (microdata_flow_id);

SELECT microdata_ensure_partition(microdata_flow_id, reporting_period)
FROM (SELECT DISTINCT microdata_flow_id, reporting_period FROM microdata_record_unpartitioned) p;

INSERT INTO microdata_record SELECT * FROM microdata_record_unpartitioned;
SELECT setval(pg_get_serial_sequence('microdata_record', 'id'),
              greatest((SELECT max(id) FROM microdata_record), 1));
DROP TABLE microdata_record_unpartitioned;

-- unique keys of a partitioned table contain its partition columns
ALTER TABLE microdata_record ADD PRIMARY KEY (id, microdata_flow_id, reporting_period);
CREATE UNIQUE INDEX microdata_record_current_uq
    ON microdata_record (microdata_flow_id, entity_id, reporting_period, stage) WHERE valid_to IS NULL;
CREATE INDEX microdata_record_current_filter_ix
    ON microdata_record (microdata_flow_id, stage, facet1_value, facet2_value, facet3_value, facet4_value)
    WHERE valid_to IS NULL;
CREATE INDEX microdata_record_current_order_ix
    ON microdata_record (stage, microdata_flow_id, reporting_period, entity_id) INCLUDE (id)
    WHERE valid_to IS NULL;
CREATE INDEX microdata_record_history_ix
    ON microdata_record (microdata_flow_id, entity_id, reporting_period, stage, valid_from);
CREATE INDEX microdata_record_entity_trgm_ix
    ON microdata_record USING gin (entity_id gin_trgm_ops) WITH (gin_pending_list_limit = 65536)
    WHERE valid_to IS NULL;

-- pending changes ----------------------------------------------------------------------------

CREATE TABLE microdata_pending (
    record_id          BIGINT PRIMARY KEY,
    microdata_flow_id  BIGINT NOT NULL,
    reporting_period   VARCHAR(32) NOT NULL,
    entity_id          VARCHAR(128) NOT NULL
);
CREATE INDEX microdata_pending_flow_ix
    ON microdata_pending (microdata_flow_id, reporting_period, entity_id);

INSERT INTO microdata_pending (record_id, microdata_flow_id, reporting_period, entity_id)
SELECT a.id, a.microdata_flow_id, a.reporting_period, a.entity_id
FROM microdata_record a
LEFT JOIN microdata_record b
       ON b.microdata_flow_id = a.microdata_flow_id AND b.entity_id = a.entity_id
      AND b.reporting_period = a.reporting_period AND b.stage = 'BETA' AND b.valid_to IS NULL
WHERE a.stage = 'ALPHA' AND a.valid_to IS NULL
  AND b.payload_json IS DISTINCT FROM a.payload_json;

-- new current Alpha vintages are pending unless Beta holds the same payload
CREATE FUNCTION microdata_pending_after_insert() RETURNS trigger AS $$
BEGIN
    IF current_setting('sdmxdw.bulk_load', true) = 'on' THEN
        RETURN NULL;
    END IF;
    INSERT INTO microdata_pending (record_id, microdata_flow_id, reporting_period, entity_id)
    SELECT n.id, n.microdata_flow_id, n.reporting_period, n.entity_id
    FROM new_rows n
    WHERE n.stage = 'ALPHA' AND n.valid_to IS NULL
      AND NOT EXISTS (
          SELECT 1 FROM microdata_record b
          WHERE b.microdata_flow_id = n.microdata_flow_id AND b.entity_id = n.entity_id
            AND b.reporting_period = n.reporting_period AND b.stage = 'BETA'
            AND b.valid_to IS NULL AND b.payload_json = n.payload_json);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- closed vintages are no longer pending (their successors decide for themselves)
CREATE FUNCTION microdata_pending_after_update() RETURNS trigger AS $$
BEGIN
    IF current_setting('sdmxdw.bulk_load', true) = 'on' THEN
        RETURN NULL;
    END IF;
    DELETE FROM microdata_pending p
    USING new_rows n
    WHERE p.record_id = n.id AND n.valid_to IS NOT NULL;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER microdata_pending_insert AFTER INSERT ON microdata_record
    REFERENCING NEW TABLE AS new_rows
    FOR EACH STATEMENT EXECUTE FUNCTION microdata_pending_after_insert();
CREATE TRIGGER microdata_pending_update AFTER UPDATE ON microdata_record
    REFERENCING NEW TABLE AS new_rows
    FOR EACH STATEMENT EXECUTE FUNCTION microdata_pending_after_update();

-- partitioned tables are never analysed by autovacuum; the planner needs their statistics
ANALYZE microdata_record;
